    template = (ROOT / 'tools' / 'home_template.html').read_text(encoding='utf-8')
    keys = set(RU)
    for name, d in (('uz', UZ), ('en', EN)):
        missing, extra = keys - set(d), set(d) - keys
        assert not missing and not extra, f'{name}: missing {missing}, extra {extra}'
    pages = {
        'index.html': ('ru', RU, 'https://squadplayers.com/'),
        'ru/index.html': ('ru', RU, 'https://squadplayers.com/ru/index.html'),
        'uz/index.html': ('uz', UZ, 'https://squadplayers.com/uz/index.html'),
        'en/index.html': ('en', EN, 'https://squadplayers.com/en/index.html'),
    }
    for path, (lang, data, canonical) in pages.items():
        (ROOT / path).write_text(render(template, lang, data, canonical), encoding='utf-8')
        print('built', path)


